/**
 * External export contract strictly from page 15 of the official brief.
 * Do NOT add additional fields to this object during export.
 */
export type TranscriptUtterance = {
  speaker_id: string; // e.g. "speaker_1"
  start_ms: number;   // integer milliseconds
  end_ms: number;     // integer milliseconds
  text: string;       // utterance text
};

export type TranscriptExport = {
  transcript: TranscriptUtterance[];
};

export type ProcessingStage =
  | 'idle'
  | 'preparing'
  | 'diarizing'
  | 'transcribing'
  | 'summarizing'
  | 'saving'
  | 'done'
  | 'error';

export type ProcessingProgress = {
  stage: ProcessingStage;
  message?: string;
  completed?: number;
  total?: number;
  percentage?: number;
};

/**
 * Internal storage format for history and UI state.
 * Preserves custom speaker names and LLM summary separately.
 */
export type SavedTranscript = {
  id: string;
  title: string;
  fileName: string;
  fileUri?: string;
  fileSize?: number;
  durationMs?: number;
  createdAt: string; // ISO 8601
  exportData: TranscriptExport;
  summary?: string; // Summary generated by local LLM
  speakerNames?: Record<string, string>; // e.g. { "speaker_1": "Кот в очках (Аналитик)" }
};

export type EngineCapabilities = {
  asr: boolean;
  diarization: boolean;
  llm: boolean;
  nativeLoaded: boolean;
};
