const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const theme = require('../src/theme/tokens.json');
const kebab = value => value.replace(/[A-Z]/g, letter => '-' + letter.toLowerCase());
const content = `/* Generated by npm run theme:generate from src/theme/tokens.json. */
@import 'tailwindcss';
@import 'uniwind';

@theme {
${Object.entries(theme.colors).map(([key, value]) => `  --color-${kebab(key)}: ${value};`).join('\n')}
  --radius-sm: ${theme.radius.sm}px;
  --radius-md: ${theme.radius.md}px;
  --radius-lg: ${theme.radius.lg}px;
  --radius-xl: ${theme.radius.xl}px;
}
`;
const output = path.join(root, 'global.css');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content) {
    throw new Error('global.css is out of sync. Run npm run theme:generate.');
  }
} else fs.writeFileSync(output, content);
